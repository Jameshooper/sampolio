import { describe, it, expect, afterEach } from 'vitest';
import { generateOccurrenceDates, toCents, resolveSplit } from './split-utils';
import { computeTripHours, computeSliceCount, generateTripDays } from './per-diem-utils';
import { generateMonthList, roundMoney, MAX_PROJECTION_MONTHS } from './projection';
import { calculateNetSalary } from './salary-utils';
import { splitSpecSchema } from './schemas/split.schema';
import type { FinancialAccount } from '@/types';

describe('split recurrence keeps month-end and leap days', () => {
  it('monthly rule on the 31st clamps per month instead of drifting to the 28th', () => {
    expect(generateOccurrenceDates({ interval: 'monthly', anchorDate: '2026-01-31' }, '2026-05-31')).toEqual([
      '2026-01-31',
      '2026-02-28',
      '2026-03-31',
      '2026-04-30',
      '2026-05-31',
    ]);
  });

  it('yearly rule on Feb 29 returns to Feb 29 in leap years', () => {
    expect(generateOccurrenceDates({ interval: 'yearly', anchorDate: '2024-02-29' }, '2028-12-31')).toEqual([
      '2024-02-29',
      '2025-02-28',
      '2026-02-28',
      '2027-02-28',
      '2028-02-29',
    ]);
  });

  it('resuming after lastGeneratedThrough matches a full run', () => {
    const full = generateOccurrenceDates({ interval: 'monthly', anchorDate: '2026-01-31' }, '2026-12-31');
    const resumed = generateOccurrenceDates(
      { interval: 'monthly', anchorDate: '2026-01-31', lastGeneratedThrough: full[5] },
      '2026-12-31'
    );
    expect([...full.slice(0, 6), ...resumed]).toEqual(full);
  });

  it('does not add a second occurrence in a month already generated by the old drifting logic', () => {
    // The previous implementation produced 2026-03-28 for a Jan-31 rule.
    const next = generateOccurrenceDates(
      { interval: 'monthly', anchorDate: '2026-01-31', lastGeneratedThrough: '2026-03-28' },
      '2026-05-31'
    );
    expect(next).toEqual(['2026-04-30', '2026-05-31']);
  });

  it('weekly and biweekly rules are unchanged', () => {
    expect(generateOccurrenceDates({ interval: 'weekly', anchorDate: '2026-03-25' }, '2026-04-08')).toEqual([
      '2026-03-25',
      '2026-04-01',
      '2026-04-08',
    ]);
    expect(generateOccurrenceDates({ interval: 'biweekly', anchorDate: '2026-03-25' }, '2026-04-22')).toEqual([
      '2026-03-25',
      '2026-04-08',
      '2026-04-22',
    ]);
  });
});

describe('cents and money rounding', () => {
  it('toCents rounds half-cents away from zero despite binary floats', () => {
    expect(toCents(1.005)).toBe(101);
    expect(toCents(1.015)).toBe(102);
    expect(toCents(-1.005)).toBe(-101);
    expect(toCents(0.1 + 0.2)).toBe(30);
    expect(toCents(8.675)).toBe(868);
    expect(toCents(1234567.89)).toBe(123456789);
    expect(Object.is(toCents(-0.001), 0)).toBe(true);
  });

  it('roundMoney removes float noise', () => {
    expect(roundMoney(2500.55 - 950)).toBe(1550.55);
    expect(roundMoney(0.1 + 0.2)).toBe(0.3);
    expect(roundMoney(-1.005)).toBe(-1.01);
  });

  it('net salary is whole cents', () => {
    const net = calculateNetSalary(3333.33, 21.5, 7.15);
    expect(Math.round(net * 100) / 100).toBe(net);
  });
});

describe('split weights', () => {
  const members = ['alex', 'sam'];

  it('rejects negative or non-finite weights in the schema', () => {
    expect(splitSpecSchema.safeParse({ paidByUserId: 'alex', splitMode: 'percent', splitConfig: { alex: -1000, sam: 1001 } }).success).toBe(false);
    expect(splitSpecSchema.safeParse({ paidByUserId: 'alex', splitMode: 'shares', splitConfig: { alex: 1, sam: 2 } }).success).toBe(true);
  });

  it('rejects negative weights in the engine (defence in depth)', () => {
    expect(() => resolveSplit(members, 100, { paidByUserId: 'alex', splitMode: 'percent', splitConfig: { alex: -1000, sam: 1001 } })).toThrow();
    expect(() => resolveSplit(members, 100, { paidByUserId: 'alex', splitMode: 'exact', splitConfig: { alex: -900, sam: 1000 } })).toThrow();
  });

  it('a member can never be owed more than the expense through weights', () => {
    const r = resolveSplit(members, 100, { paidByUserId: 'alex', splitMode: 'percent', splitConfig: { alex: 0, sam: 100 } });
    expect(r.netByUserId).toEqual({ alex: 100, sam: -100 });
  });
});

describe('per-diem is independent of the host time zone', () => {
  const original = process.env.TZ;
  afterEach(() => {
    process.env.TZ = original;
  });

  for (const tz of ['UTC', 'Europe/Helsinki', 'America/New_York', 'Australia/Lord_Howe']) {
    it(`measures wall-clock days across DST changes (${tz})`, () => {
      process.env.TZ = tz;
      expect(computeTripHours('2026-03-28T08:00', '2026-03-29T08:00')).toEqual({ totalHours: 24, fullDays: 1, remainderHours: 0 });
      expect(computeTripHours('2026-10-24T08:00', '2026-10-25T08:00')).toEqual({ totalHours: 24, fullDays: 1, remainderHours: 0 });
      expect(computeSliceCount('2026-10-24T08:00', '2026-10-26T10:00')).toBe(3);
      expect(generateTripDays('2026-10-24T08:00', '2026-10-26T10:00', 'SE').map((d) => d.date)).toEqual([
        '2026-10-24',
        '2026-10-25',
        '2026-10-26',
      ]);
    });
  }
});

describe('projection length is bounded', () => {
  const account = (customEndDate?: string): FinancialAccount =>
    ({ startingDate: '2026-01', planningHorizonMonths: 120, customEndDate } as FinancialAccount);

  it('caps a far-future custom end date', () => {
    const t0 = Date.now();
    const months = generateMonthList(account('9999-12'));
    expect(months).toHaveLength(MAX_PROJECTION_MONTHS);
    expect(Date.now() - t0).toBeLessThan(1000);
  });

  it('keeps normal horizons exact', () => {
    expect(generateMonthList(account())).toHaveLength(120);
    expect(generateMonthList(account('2026-12'))).toHaveLength(12);
  });
});
